import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const sourcePath = path.join(root, "素材", "人物清单.md");
const jsonPath = path.join(root, "src", "media-assets", "people-catalog.json");
const tsPath = path.join(root, "src", "media-assets", "people-catalog.ts");

const text = await readFile(sourcePath, "utf8");
let category = "未分类";
let priority = "P1";
const byId = new Map();

for (const line of text.split(/\r?\n/)) {
  const categoryMatch = line.match(/^#\s+[^、]+、(.+)$/);
  if (categoryMatch) category = categoryMatch[1].trim();
  const priorityMatch = line.match(/^##\s+(P[01])/);
  if (priorityMatch) priority = priorityMatch[1];
  const cells = line.split("|").map((cell) => cell.trim());
  if (cells.length < 4) continue;
  const idMatch = cells[2]?.match(/`([a-z0-9_]+)`/);
  if (!idMatch) continue;
  const id = idMatch[1];
  const name = cells[1].replace(/\*\*/g, "").trim();
  const role = (cells[3] ?? "").trim();
  const existing = byId.get(id) ?? { id, name, aliases: [], roles: [], categories: [], priorities: [] };
  if (role && !existing.roles.includes(role)) existing.roles.push(role);
  if (!existing.categories.includes(category)) existing.categories.push(category);
  if (!existing.priorities.includes(priority)) existing.priorities.push(priority);
  byId.set(id, existing);
}

const entries = [...byId.values()].sort((a, b) => {
  const priority = Number(b.priorities.includes("P0")) - Number(a.priorities.includes("P0"));
  return priority || a.id.localeCompare(b.id);
});

await mkdir(path.dirname(jsonPath), { recursive: true });
await writeFile(jsonPath, `${JSON.stringify(entries, null, 2)}\n`);
await writeFile(
  tsPath,
  `// Generated by scripts/build-person-catalog.mjs from 素材/人物清单.md.\n` +
    `import type { PersonCatalogEntry } from "./types.ts";\n\n` +
    `export const personCatalog = ${JSON.stringify(entries, null, 2)} as const satisfies readonly PersonCatalogEntry[];\n\n` +
    `export type PersonId = (typeof personCatalog)[number]["id"];\n` +
    `export const personCatalogById = new Map(personCatalog.map((person) => [person.id, person]));\n`,
);

console.log(
  `Generated ${entries.length} unique people from ${[...byId.values()].reduce((n, entry) => n + entry.categories.length, 0)} category registrations.`,
);
