import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const manifestPath = path.join(root, "public/media-assets/people/manifest.json");
const outputPath = path.join(root, "src/media-assets/person-assets.ts");
const assets = JSON.parse(await readFile(manifestPath, "utf8"));
for (const asset of assets) {
  if (asset.kind !== "person") continue;
  const chineseName = [...asset.label.matchAll(/[\u3400-\u9fff]/g)].map((match) => match[0]).join("");
  if (chineseName) asset.fallback = { type: "monogram", value: chineseName };
}
await writeFile(manifestPath, `${JSON.stringify(assets, null, 2)}\n`);

await writeFile(
  outputPath,
  `// Generated by scripts/build-media-registry.mjs.\n` +
    `import type { MediaAssetDefinition } from "./types.ts";\n\n` +
    `export const personAssets = ${JSON.stringify(assets, null, 2)} as const satisfies readonly MediaAssetDefinition[];\n\n` +
    `export type RegisteredPersonId = (typeof personAssets)[number]["id"];\n` +
    `export const personAssetById = new Map(personAssets.map((asset) => [asset.id, asset]));\n`,
);

console.log(`Generated runtime registry for ${assets.length} people.`);
